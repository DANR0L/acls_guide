import re

with open('lib/data/algorithms.dart', 'r', encoding='utf-8') as f:
    text = f.read()

with open('scratch_stroke.dart', 'r', encoding='utf-8') as f:
    new_stroke = f.read()

# The string new_stroke already contains import '../models/algorithm_node.dart';, so we strip it.
new_stroke = new_stroke.replace("import '../models/algorithm_node.dart';\n\n", "")

pattern = r"final strokeAlgorithm = Algorithm\([\s\S]*?(?=\n// \?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?|final allAlgorithms = <String, Algorithm>\{)"

result = re.sub(pattern, new_stroke + "\n\n", text)

with open('lib/data/algorithms.dart', 'w', encoding='utf-8') as f:
    f.write(result)
